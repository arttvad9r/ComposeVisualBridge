import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';
import { spawn, execFile } from 'node:child_process';
import { once } from 'node:events';
const baseline = JSON.parse(await readFile(new URL('../examples/browser-scenarios.json', import.meta.url)));
baseline.sourceRevision = 'native-source-sha256';
const png = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aWQAAAABJRU5ErkJggg==';
test('baseline proof gates review, persists, and stays bound to an immutable snapshot', async t => {
  const data = await mkdtemp(path.join(tmpdir(), 'bridge-proof-'));
  await writeFile(path.join(data, 'session.json'), JSON.stringify({revision:0, baseline, current:baseline, applied:null}));
  let child;
  const stop = async () => { if (child && child.exitCode === null) { const done = once(child,'exit'); child.kill(); await done; } };
  t.after(async () => { await stop(); await rm(data,{recursive:true,force:true}); });
  const start = async () => {
    child = spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:'0',BRIDGE_DATA:data},stdio:['ignore','pipe','pipe']});
    return new Promise((resolve,reject) => { let output=''; child.stdout.on('data', c => { output+=c; const match=output.match(/http:\/\/127\.0\.0\.1:\d+/); if(match)resolve(match[0]); }); child.once('error',reject); child.once('exit',()=>reject(Error('Сервер завершился'))); });
  };
  let url = await start();
  await assert.rejects(promisify(execFile)(process.execPath,['server.mjs'],{env:{...process.env,PORT:'0',BRIDGE_DATA:data},timeout:3000}),/сессия уже открыта/);
  const request = async (endpoint, payload, method='POST') => { const response=await fetch(url+endpoint,payload?{method,headers:{'content-type':'application/json'},body:JSON.stringify(payload)}:{}); return {status:response.status, value:await response.json()}; };
  let state=(await request('/api/session')).value;
  const blocked=await request('/api/apply',{revision:state.revision,document:baseline,mode:'review'});
  assert.equal(blocked.status,422);
  assert.equal((await request('/api/session')).value.revision,0);
  assert.equal((await request('/api/baseline/confirm',{revision:0,baselineFingerprint:state.baselineFingerprint,acknowledged:true})).status,400);
  state=(await request('/api/baseline/reference',{revision:0,image:png,mime:'image/png',label:'Настройки, Android, 412 × 1100 dp'})).value;
  assert.equal(state.verification,null);
  assert.equal((await request('/api/baseline/confirm',{revision:state.revision,baselineFingerprint:'stale',acknowledged:true})).status,400);
  state=(await request('/api/baseline/confirm',{revision:state.revision,baselineFingerprint:state.baselineFingerprint,acknowledged:true})).value;
  assert.equal(state.verification.confirmedBy,'user');
  assert.equal(state.verification.bridgeVersion,state.bridgeVersion);
  const changed=structuredClone(baseline); changed.root.children[0].props.text='Правка пользователя';
  changed.layout={mode:'free',frames:{screen:{parent:null,x:0,y:0,width:412,height:1100}}};
  state=(await request('/api/apply',{revision:state.revision,document:changed,mode:'review'})).value;
  const handoff=(await request('/api/handoff')).value;
  assert.deepEqual(handoff.baseline,baseline);
  assert.equal(handoff.verification.baselineFingerprint,state.baselineFingerprint);
  assert.equal(handoff.intent.changes.some(c=>c.property==='layout'),false);
  assert.equal(handoff.intent.technical.length,1);
  assert.match(handoff.report,/Проверка исходного/);
  await stop(); url=await start();
  assert.deepEqual((await request('/api/handoff')).value,handoff);
  const corrected=structuredClone(baseline); corrected.name='Исправленная реконструкция';
  state=(await request('/api/session',{revision:state.revision,document:corrected},'PUT')).value;
  assert.equal(state.verification,null); assert.equal(state.reference,null); assert.ok(state.previousSession);
  state=(await request('/api/session/restore',{revision:state.revision})).value;
  assert.deepEqual(state.current,changed); assert.deepEqual(state.baseline,baseline);
  assert.equal(state.verification.confirmedBy,'user'); assert.deepEqual((await request('/api/handoff')).value,handoff);
  const invalid=await request('/api/baseline/reference',{revision:state.revision,image:'YWJjZA==',mime:'image/png',label:'Повреждённый'});
  assert.equal(invalid.status,400); assert.equal((await request('/api/session')).value.verification.confirmedBy,'user');
  state=(await request('/api/baseline/reference',{revision:state.revision,image:png,mime:'image/png',label:'Другой эталон'})).value;
  assert.equal(state.verification,null);
  assert.deepEqual((await request('/api/handoff')).value,handoff);
  assert.equal((await request('/api/apply',{revision:state.revision,document:changed,mode:'review'})).status,422);
  const testSnapshot=await request('/api/apply',{revision:state.revision,document:changed,mode:'test'});
  assert.equal(testSnapshot.status,200);
});
test('JVM-rendered Preview baseline is verified by the render itself', async () => {
  const { readReference, renderedVerification, isVerified, publicSession } = await import('../baseline.mjs');
  const state = { revision:0, baseline, current:baseline, applied:null, reference:readReference({mime:'image/png',image:png,label:'Превью'}) };
  state.verification = renderedVerification(state);
  assert.equal(isVerified(state), true); assert.equal(publicSession(state).verification.confirmedBy, 'render');
  assert.equal(isVerified({ ...state, baseline:{ ...baseline, name:'другой' } }), false);
  assert.equal(isVerified({ ...state, verification:{ ...state.verification, confirmedBy:'agent' } }), false);
});
